USE DATABASE NETSUITE_FINANCE_DEMO;
USE SCHEMA CONFORMED;

CREATE OR REPLACE TABLE DIM_ACCOUNT AS
SELECT
    ACCOUNT_ID,
    ACCOUNT_NUMBER,
    ACCOUNT_NAME,
    ACCOUNT_TYPE,
    IS_INACTIVE,
    LAST_MODIFIED_AT
FROM RAW.ACCOUNT
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY ACCOUNT_ID
    ORDER BY LAST_MODIFIED_AT DESC, INGESTED_AT DESC
) = 1;

