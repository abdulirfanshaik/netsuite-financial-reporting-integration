CREATE OR REPLACE TABLE FACT_GL_LINE AS
SELECT
    L.TRANSACTION_ID,
    L.LINE_ID,
    H.TRANSACTION_NUMBER,
    H.TRANSACTION_TYPE,
    H.TRANSACTION_DATE,
    H.POSTING_PERIOD_ID,
    COALESCE(L.SUBSIDIARY_ID, H.SUBSIDIARY_ID) AS SUBSIDIARY_ID,
    L.ACCOUNT_ID,
    L.DEPARTMENT_ID,
    L.CLASS_ID,
    COALESCE(L.CURRENCY_ID, H.CURRENCY_ID) AS CURRENCY_ID,
    H.EXCHANGE_RATE,
    H.POSTING_FLAG,
    COALESCE(L.DEBIT_AMOUNT, 0) AS DEBIT_AMOUNT,
    COALESCE(L.CREDIT_AMOUNT, 0) AS CREDIT_AMOUNT,
    COALESCE(L.DEBIT_AMOUNT, 0) - COALESCE(L.CREDIT_AMOUNT, 0) AS SIGNED_AMOUNT,
    L.FOREIGN_AMOUNT,
    H.MEMO AS TRANSACTION_MEMO,
    L.LINE_MEMO,
    GREATEST(H.LAST_MODIFIED_AT, L.LAST_MODIFIED_AT) AS LAST_MODIFIED_AT
FROM RAW.TRANSACTION_HEADER H
JOIN RAW.TRANSACTION_LINE L
  ON H.TRANSACTION_ID = L.TRANSACTION_ID
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY L.TRANSACTION_ID, L.LINE_ID
    ORDER BY GREATEST(H.LAST_MODIFIED_AT, L.LAST_MODIFIED_AT) DESC,
             H.INGESTED_AT DESC,
             L.INGESTED_AT DESC
) = 1;
